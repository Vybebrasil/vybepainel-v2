import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {conexao} from './postgres.mjs';
const migracao=readFileSync('migrations/2026-10-18-escritorio-reinicio-reembolso.sql','utf8');
test('reinício devolve compras uma vez, sem XP, preserva conquistas e salas comuns',async t=>{
 const {db}=conexao();t.after(()=>db.close());
 await db.exec(`CREATE TABLE vybe_escritorio_perfis(pessoa_id bigint,preferencias jsonb,atualizado_em timestamptz);
 CREATE TABLE vybe_escritorio_mapa(camada text,itens jsonb,versao int,atualizado_em timestamptz);
 CREATE TABLE vybe_escritorio_mapa_versoes(camada text);
 CREATE TABLE vybe_escritorio_inventario(pessoa_id bigint,classe text,quantidade int);
 CREATE TABLE vybe_escritorio_carteiras(pessoa_id bigint PRIMARY KEY,saldo int);
 CREATE TABLE vybe_escritorio_moedas(id bigserial,pessoa_id bigint,origem text,quantidade int,pontos int DEFAULT 0,UNIQUE(pessoa_id,origem));
 INSERT INTO vybe_escritorio_perfis VALUES(1,'{"sala_planta":"amplo","sala_celdas":"pp","sala_andares":[{}],"sala_pisos":"abc","quarto_configurado":true,"figura":"hd-180-1","sala":"cafe"}',now());
 INSERT INTO vybe_escritorio_mapa VALUES('sala-0','[["chair",1,1,2]]',3,now()),('sala-0-andar-1','[["chair",1,1,2]]',4,now()),('cafe','[["chair",1,1,2]]',7,now());
 INSERT INTO vybe_escritorio_mapa_versoes VALUES('sala-0'),('cafe');
 INSERT INTO vybe_escritorio_inventario VALUES(1,'chair',2);
 INSERT INTO vybe_escritorio_carteiras VALUES(1,30);
 INSERT INTO vybe_escritorio_moedas(pessoa_id,origem,quantidade,pontos) VALUES(1,'compra:a:chair',-25,0),(1,'compra:b:chair',-80,0),(1,'conquista:um',50,50),(2,'compra:c:chair',-10,0);`);
 await db.exec(migracao);
 assert.deepEqual((await db.query('SELECT saldo FROM vybe_escritorio_carteiras ORDER BY pessoa_id')).rows,[{saldo:135},{saldo:10}]);
 assert.equal((await db.query('SELECT sum(pontos)::int AS xp FROM vybe_escritorio_moedas')).rows[0].xp,50);
 const perfil=(await db.query('SELECT preferencias FROM vybe_escritorio_perfis')).rows[0].preferencias;
 assert.deepEqual(perfil,{figura:'hd-180-1',sala:'cafe',quarto_configurado:false});
 const camadas=(await db.query('SELECT camada,itens,versao FROM vybe_escritorio_mapa ORDER BY camada')).rows;
 assert.equal(camadas[0].itens.length,1);assert.equal(camadas[0].versao,7);assert.equal(camadas[1].itens.length,0);
 assert.equal((await db.query('SELECT * FROM vybe_escritorio_inventario')).rows.length,0);
 await db.exec(`INSERT INTO vybe_escritorio_inventario VALUES(1,'nova',1); UPDATE vybe_escritorio_perfis SET preferencias='{"quarto_configurado":true}';`);
 await db.exec(migracao);
 assert.equal((await db.query('SELECT saldo FROM vybe_escritorio_carteiras WHERE pessoa_id=1')).rows[0].saldo,135);
 assert.equal((await db.query('SELECT * FROM vybe_escritorio_inventario')).rows.length,1);
 assert.equal((await db.query('SELECT preferencias FROM vybe_escritorio_perfis')).rows[0].preferencias.quarto_configurado,true);
});
